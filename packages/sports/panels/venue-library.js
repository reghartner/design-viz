/* Venue library for the seatmap panel. A venue is plain data: a name, a
   location, an honesty note and the seatmap declaration fields that describe
   its seating (geometry, bowl, rings, sections, landmarks, …). Upstream venues
   live one per file in packages/sports/panels/venues/*.js and a fork adds its own in
   company/panels/venues/*.js; both directories are discovered by
   src/source-bundles.json, so adding a venue never edits an upstream file.
   Each file is generated by `tools/seatmap-import.mjs --venue …` and holds a
   single SeatmapVenues.define({...}) call with a JSON literal.

   A seatmap panel references a venue with `"venue": "<id>"`. Each field in
   SEATMAP_VENUE_FIELDS that the panel writes itself replaces the venue's
   value for that field wholesale (arrays are never merged); every other
   field comes from the venue. Depends only on packages/sports/panels/sports.js. */
var SEATMAP_VENUE_FIELDS = ['geometry', 'bowl', 'direction', 'startAt', 'ringSlots', 'viewBox', 'field', 'rings', 'sections', 'landmarks'];
var SEATMAP_VENUE_TEXT = { name: 60, location: 60, note: 300, capacityNote: 80 };
var SeatmapVenues = (function () {
  var venues = Object.create(null), order = [];
  function isObject(v) { return !!v && typeof v === 'object' && !Array.isArray(v); }
  function own(obj, key) { return isObject(obj) && Object.prototype.hasOwnProperty.call(obj, key); }
  function freeze(value) {
    if (value && typeof value === 'object') {
      Object.keys(value).forEach(function (key) { freeze(value[key]); });
      Object.freeze(value);
    }
    return value;
  }
  function fail(id, message) { throw new Error('Seatmap venue ' + JSON.stringify(id) + ': ' + message); }
  /* Registration runs at load time, so a malformed or duplicate venue file
     fails the build and every test that assembles the sources. */
  function define(entry) {
    if (!isObject(entry)) throw new Error('Seatmap venue: expected one object');
    var id = entry.id;
    if (!spmSafeId(id)) fail(id, 'id must be a letter-or-digit-led id of up to 32 characters');
    if (venues[id]) fail(id, 'is already defined; venue ids are unique across packages/sports/panels/venues and company/panels/venues');
    Object.keys(entry).forEach(function (key) {
      if (key !== 'id' && key !== 'seatmap' && !own(SEATMAP_VENUE_TEXT, key)) fail(id, 'unknown field "' + key + '"');
    });
    Object.keys(SEATMAP_VENUE_TEXT).forEach(function (key) {
      var v = entry[key], max = SEATMAP_VENUE_TEXT[key];
      if (v === undefined && key !== 'name') return;
      if (typeof v !== 'string' || !v.trim() || v.length > max || /[\u0000-\u001f\u007f<>]/.test(v))
        fail(id, key + ' must be 1–' + max + ' characters of plain text');
    });
    if (!isObject(entry.seatmap)) fail(id, 'seatmap must be an object of seatmap declaration fields');
    Object.keys(entry.seatmap).forEach(function (key) {
      if (SEATMAP_VENUE_FIELDS.indexOf(key) < 0) fail(id, 'seatmap.' + key + ' is not a venue field (' + SEATMAP_VENUE_FIELDS.join(', ') + ')');
    });
    if (!Array.isArray(entry.seatmap.rings) || !Array.isArray(entry.seatmap.sections))
      fail(id, 'seatmap needs rings and sections arrays');
    /* A JSON round trip drops anything that is not plain data. */
    venues[id] = freeze(JSON.parse(JSON.stringify(entry)));
    order.push(id);
    return venues[id];
  }
  function get(id) {
    return typeof id === 'string' && Object.prototype.hasOwnProperty.call(venues, id) ? venues[id] : null;
  }
  function ids() { return order.slice(); }
  /* Picker rows in definition order: upstream files by name, then fork files. */
  function list() {
    return order.map(function (id) {
      var v = venues[id];
      return { id: id, name: v.name, location: v.location || '', note: v.note || '', capacityNote: v.capacityNote || '', sections: v.seatmap.sections.length };
    });
  }
  /* The declaration a seatmap panel actually draws: the panel's own fields,
     plus each venue field the panel does not write. A panel without `venue`,
     or with an unknown id, is returned unchanged (the same object). */
  function resolve(panel) {
    if (!own(panel, 'venue')) return panel;
    var venue = get(panel.venue);
    if (!venue) return panel;
    var out = {};
    Object.keys(panel).forEach(function (key) { out[key] = panel[key]; });
    SEATMAP_VENUE_FIELDS.forEach(function (key) {
      if (!own(panel, key) && own(venue.seatmap, key)) out[key] = venue.seatmap[key];
    });
    return out;
  }
  return { define: define, get: get, ids: ids, list: list, resolve: resolve, fields: SEATMAP_VENUE_FIELDS.slice() };
})();
