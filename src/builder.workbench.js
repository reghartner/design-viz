  function runInsert(kind, planFn){
    var parsed = parseEditor();
    if (parsed.error){ inspectorMessage(parsed.error + ' — fix it before inserting'); return; }
    if (kind !== 'section' && !specSectionPaths(parsed.raw).length){
      inspectorMessage('no sections found in the editor text'); return;
    }
    var plan = kind === 'section' ? planAddSection(src.value, parsed.raw)
                                  : planFn(src.value, parsed.raw, insertSection);
    if (plan.error){ inspectorMessage(plan.error); return; }
    pushUndo();
    clearMultiSelect(); /* this action establishes a single selection */
    src.value = plan.text;
    render();
    autosaveDraft();
    if (plan.kind === 'section') insertSection = plan.index;
    var identity = {section: plan.kind === 'section' ? plan.index : insertSection,
                    kind: plan.kind, id: plan.id, index: plan.index};
    var el = findTargetEl(identity);
    selectTarget({section: identity.section, kind: identity.kind, id: identity.id,
                  index: identity.index, el: el}, false);
    selectRange(plan);
  }
  var addButtons = {
    'add-step': ['step', planAddStep],
    'add-section': ['section', planAddSection]
  };
  Object.keys(addButtons).forEach(function(id){
    var btn = document.getElementById(id);
    if (btn) btn.addEventListener('click', function(){
      runInsert(addButtons[id][0], addButtons[id][1]);
    });
  });
  /* + edge draws by clicking source then target (Esc cancels) */
  var edgeBtn = document.getElementById('add-edge');
  if (edgeBtn) edgeBtn.addEventListener('click', startConnect);
  /* + tabs appends a whole tabs container and lands on its first tab —
     tab targets address by block/tab, so runInsert's section identity
     does not fit */
  var tabsBtn = document.getElementById('add-tabs');
  if (tabsBtn) tabsBtn.addEventListener('click', function(){
    var parsed = parseEditor();
    if (parsed.error){ inspectorMessage(parsed.error + ' — fix it before inserting'); return; }
    var plan = planAddTabs(src.value, parsed.raw);
    if (plan.error){ inspectorMessage(plan.error); return; }
    pushUndo();
    clearMultiSelect(); /* this action establishes a single selection */
    src.value = plan.text;
    render();
    autosaveDraft();
    insertSection = plan.index; /* inserts now land in the first new tab's section */
    var el = findTargetEl({kind: 'tab', block: plan.block, tab: 0});
    selectTarget({kind: 'tab', block: plan.block, tab: 0, el: el}, false);
    selectRange(plan);
  });

  /* ---- starter gallery: whole-editor replacement is one undo action ---- */
  var gallery = document.getElementById('gallery');
  var startersBtn = document.getElementById('starters');
  var starterUndoText = null;
  function closeGallery(){
    if (!gallery) return;
    gallery.hidden = true;
    gallery.innerHTML = '';
    if (startersBtn) startersBtn.setAttribute('aria-expanded', 'false');
  }
  function loadStarter(entry){
    if (addToStep) return;
    pushUndo();
    src.value = JSON.stringify(entry.spec, null, 2);
    starterUndoText = src.value;
    setSelected(null); currentTarget = null; insertSection = 0;
    if (connect) cancelConnect();
    clearStepMarkers();
    render();
    updateTargetLabel(entry.spec);
    if (guide) guide.hidden = true;
    autosaveDraft();
    closeGallery();
    src.focus();
  }
  /* the external manifest is fetched once at boot; editing starters.json
     and reloading the page picks up additions (no rebuild anywhere) */
  var externalStarters = null; /* {entries, skipped} or {error} once loaded */
  if (typeof fetch === 'function'){
    fetch('starters.json', {cache: 'no-store'}).then(function(resp){
      if (!resp.ok) throw new Error('HTTP ' + resp.status);
      return resp.text();
    }).then(function(text){
      externalStarters = parseStarterManifest(text);
    })['catch'](function(){ /* no manifest beside the page: baked-ins only */ });
  }
  function starterCard(entry){
    var card = document.createElement('button');
    card.type = 'button'; card.className = 'pbtn starter-card';
    var name = document.createElement('strong'); name.textContent = entry.name;
    var desc = document.createElement('span'); desc.textContent = entry.desc;
    var count = document.createElement('span'); count.textContent = starterCountLine(entry.spec);
    card.appendChild(name); card.appendChild(desc); card.appendChild(count);
    card.addEventListener('click', function(){
      if (addToStep) return;
      if (opts.renderedText && src.value === opts.renderedText()){ loadStarter(entry); return; }
      showGallery();
      var row = document.createElement('div'); row.className = 'starter-confirm';
      var label = document.createElement('span');
      label.textContent = 'unrendered edits — replace with ' + entry.name + '?';
      var load = document.createElement('button');
      load.type = 'button'; load.className = 'bbtn'; load.textContent = 'load & replace';
      load.addEventListener('click', function(){ loadStarter(entry); });
      var cancel = document.createElement('button');
      cancel.type = 'button'; cancel.className = 'bbtn'; cancel.textContent = 'cancel';
      cancel.addEventListener('click', function(){ showGallery(); gallery.querySelector('button').focus(); });
      row.appendChild(label); row.appendChild(load); row.appendChild(cancel);
      gallery.appendChild(row);
      cancel.focus();
    });
    return card;
  }
  function showGallery(){
    gallery.innerHTML = '';
    (opts.starters || []).forEach(function(entry){
      gallery.appendChild(starterCard(entry));
    });
    if (externalStarters){
      var divider = document.createElement('div');
      divider.className = 'gallery-note';
      divider.textContent = 'from starters.json';
      gallery.appendChild(divider);
      if (externalStarters.error){
        var bad = document.createElement('div');
        bad.className = 'gallery-note gallery-bad';
        bad.textContent = externalStarters.error;
        gallery.appendChild(bad);
      } else {
        externalStarters.entries.forEach(function(entry){
          gallery.appendChild(starterCard(entry));
        });
        if (externalStarters.skipped){
          var skip = document.createElement('div');
          skip.className = 'gallery-note gallery-bad';
          skip.textContent = externalStarters.skipped +
            ' entr' + (externalStarters.skipped === 1 ? 'y' : 'ies') +
            ' skipped — each needs a name and a spec object';
          gallery.appendChild(skip);
        }
      }
    }
    gallery.hidden = false;
    startersBtn.setAttribute('aria-expanded', 'true');
  }
  if (startersBtn && gallery) startersBtn.addEventListener('click', function(){
    if (addToStep) return;
    if (!gallery.hidden){ closeGallery(); return; }
    closePalette();
    showGallery();
  });
  document.addEventListener('keydown', function(ev){
    /* Programmatic textarea replacements do not enter native undo history. */
    if (!(ev.ctrlKey || ev.metaKey) || ev.altKey || ev.shiftKey || ev.key.toLowerCase() !== 'z') return;
    if (addToStep || starterUndoText === null || src.value !== starterUndoText || !undoStack.length) return;
    var ae = document.activeElement;
    if (ae && ae !== src && (ae.tagName === 'INPUT' || ae.tagName === 'TEXTAREA' || ae.isContentEditable)) return;
    ev.preventDefault();
    starterUndoText = null;
    doUndo();
  });

  /* ---- insert palettes: + node picks a preset, + panel picks a type ---- */
  var palette = document.getElementById('palette');
  function closePalette(){
    if (palette && !palette.hidden){ palette.hidden = true; palette.innerHTML = ''; }
  }
  function paletteButton(iconToken, labelText, run){
    var b = document.createElement('button');
    b.type = 'button'; b.className = 'pbtn';
    if (iconToken){
      /* iconToken comes from our own preset table, never from the spec */
      var ns = 'http://www.w3.org/2000/svg';
      var svg = document.createElementNS(ns, 'svg');
      svg.setAttribute('viewBox', '0 0 16 16');
      svg.setAttribute('aria-hidden', 'true');
      var use = document.createElementNS(ns, 'use');
      use.setAttribute('href', '#i-' + iconToken);
      svg.appendChild(use);
      b.appendChild(svg);
    }
    b.appendChild(document.createTextNode(labelText));
    b.addEventListener('click', function(){ closePalette(); run(); });
    return b;
  }
  function openPalette(kind){
    hideDiff();
    if (!palette) return;
    closeGallery();
    if (!palette.hidden && palette.getAttribute('data-kind') === kind){ closePalette(); return; }
    palette.setAttribute('data-kind', kind);
    palette.innerHTML = '';
    if (kind === 'node'){
      NODE_PRESETS.forEach(function(pr){
        palette.appendChild(paletteButton(pr.icon, pr.title, function(){
          runInsert('node', function(text, raw, si){ return planAddNode(text, raw, si, pr); });
        }));
      });
    } else {
      Object.keys(PANEL_TEMPLATES).forEach(function(type){
        palette.appendChild(paletteButton(null, type, function(){
          runInsert('panel', function(text, raw, si){ return planAddPanel(text, raw, si, type); });
        }));
      });
    }
    palette.hidden = false;
  }
  var nodeBtn = document.getElementById('add-node');
  if (nodeBtn) nodeBtn.addEventListener('click', function(){ openPalette('node'); });
  var panelBtn = document.getElementById('add-panel');
  if (panelBtn) panelBtn.addEventListener('click', function(){ openPalette('panel'); });
  document.addEventListener('click', function(ev){
    if (palette && !palette.hidden &&
        !(ev.target.closest && ev.target.closest('#palette, #add-node, #add-panel'))) closePalette();
  });

  BUILDER_JUMP_TO_FINDING = function(message, rawPath){
    var parsed = parseEditor();
    if (parsed.error) return;
    var loc = findingLocation(src.value, parsed.raw, message, rawPath);
    if (!loc) return;
    selectRange(loc, true);
    if (!loc.exact) inspectorMessage('the exact field is not in the editor text — selected its nearest parent');
  };

  var initial = parseEditor();
  updateTargetLabel(initial.error ? null : initial.raw);
  applyRowGrabs(); /* the boot render happened before this wiring ran */
