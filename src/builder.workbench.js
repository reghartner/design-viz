function diffSpecs(oldObj, newObj){
  var findings = [], ranks = new Map(), ends = new Map(), ordinal = 0;
  function object(v){ return v && typeof v === 'object' && !Array.isArray(v) ? v : {}; }
  function list(v){ return Array.isArray(v) ? v : []; }
  function index(v, path){
    ranks.set(JSON.stringify(path), ordinal++);
    if (v && typeof v === 'object') Object.keys(v).forEach(function(k){
      index(v[k], path.concat([Array.isArray(v) ? Number(k) : k]));
    });
    ends.set(JSON.stringify(path), ordinal);
  }
  index(newObj, []);
  function existing(path){
    path = path.slice();
    while (path.length && !ranks.has(JSON.stringify(path))) path.pop();
    return path;
  }
  function add(path, kind, text, order){
    var target = existing(path), key = JSON.stringify(target);
    findings.push({path: builderPathString(target), kind: kind, text: text,
      order: order == null ? (kind === 'removed' ? ends.get(key) - 0.5 : ranks.get(key)) : order,
      seq: findings.length});
  }
  function fields(a, b, keys, path, label){
    a = object(a); b = object(b);
    keys.forEach(function(k){
      if (JSON.stringify(a[k]) !== JSON.stringify(b[k]))
        add(path.concat([k]), 'changed', label + ' ' + k + ' changed');
    });
  }
  /* compare EVERY key present on either side (minus the identity keys the
     pairing used) — a whitelist here silently hides material edits like a
     node link, a panel initial, or a contract row's hot flag */
  function allFields(a, b, path, label, except){
    a = object(a); b = object(b);
    var seen = {};
    Object.keys(a).concat(Object.keys(b)).forEach(function(k){
      if (seen[k] || (except && except.indexOf(k) >= 0)) return;
      seen[k] = true;
      if (JSON.stringify(a[k]) !== JSON.stringify(b[k]))
        add(path.concat([k]), 'changed', label + ' ' + k + ' changed');
    });
  }
  /* Match full identity first; optional similarity disambiguates repeated
     headings. A unique endpoint residual allows an edge kind edit. */
  function pairs(a, b, same, score){
    var matches = new Map(), used = new Set(), candidates = [];
    a.forEach(function(x, i){ b.forEach(function(y, j){
      if (same(x, y)) candidates.push({i: i, j: j, score: score ? score(x, y) : 0});
    }); });
    candidates.sort(function(x, y){
      return y.score - x.score || Math.abs(x.i - x.j) - Math.abs(y.i - y.j) || x.i - y.i || x.j - y.j;
    });
    candidates.forEach(function(c){
      if (!used.has(c.i) && !matches.has(c.j)){ used.add(c.i); matches.set(c.j, c.i); }
    });
    return {matches: matches, used: used};
  }
  function compareList(a, b, path, key, label, except, endpoints){
    a = list(a); b = list(b);
    var match = pairs(a, b, function(x, y){
      return key(object(x)) === key(object(y)) && (!endpoints || endpoints(x) === endpoints(y));
    });
    if (endpoints) a.forEach(function(x, i){
      if (match.used.has(i)) return;
      var oldLeft = a.filter(function(v, k){ return !match.used.has(k) && endpoints(v) === endpoints(x); });
      var newLeft = b.map(function(v, j){ return j; }).filter(function(j){
        return !match.matches.has(j) && endpoints(b[j]) === endpoints(x);
      });
      if (oldLeft.length === 1 && newLeft.length === 1){ match.used.add(i); match.matches.set(newLeft[0], i); }
    });
    b.forEach(function(v, j){
      var itemPath = path.concat([j]), name = label + ' ' + key(object(v));
      if (!match.matches.has(j)) add(itemPath, 'added', name + ' added');
      else allFields(a[match.matches.get(j)], v, itemPath, name, except);
    });
    a.forEach(function(v, i){
      if (!match.used.has(i)) add(path, 'removed', label + ' ' + key(object(v)) + ' removed');
    });
  }
  function page(raw){ return object(object(raw).page || raw); }
  function sections(raw){
    var p = page(raw), base = object(raw).page ? ['page'] : [];
    var key = Array.isArray(p.blocks) ? 'blocks' : 'sections', result = [], tabs = [];
    if (p.nodes && p.rows) return {refs: [{value: {diagram: p}, path: [], diagram: []}], tabs: [], base: base};
    list(p[key]).forEach(function(b, i){
      var path = base.concat([key, i]);
      if (Array.isArray(object(b).tabs)) b.tabs.forEach(function(t, j){
        var tabPath = path.concat(['tabs', j]);
        tabs.push({value: object(t), path: tabPath});
        list(object(t).sections).forEach(function(sec, k){
          var sp = tabPath.concat(['sections', k]);
          result.push({value: object(sec), path: sp, diagram: sp.concat(['diagram'])});
        });
      });
      else result.push({value: object(b), path: path, diagram: path.concat(['diagram'])});
    });
    return {refs: result, tabs: tabs, base: base.concat([key])};
  }
  function heading(ref){ return typeof ref.value.heading === 'string' ? ref.value.heading : ''; }
  function similarity(a, b){
    var an = Object.keys(object(object(a.value.diagram).nodes));
    var bn = object(object(b.value.diagram).nodes);
    var af = list(object(a.value.contract).fields), bf = list(object(b.value.contract).fields);
    var shared = an.filter(function(k){ return Object.prototype.hasOwnProperty.call(bn, k); }).length;
    af.forEach(function(f){ if (bf.some(function(g){ return object(f).k === object(g).k; })) shared++; });
    return shared + (object(a.value.contract).title === object(b.value.contract).title ? 0.25 : 0);
  }
  var old = sections(oldObj), next = sections(newObj);
  var tabs = pairs(old.tabs, next.tabs, function(a, b){ return a.value.label === b.value.label; });
  function container(path){
    var target = null, key = JSON.stringify(path);
    tabs.matches.forEach(function(oi, ni){
      var ot = old.tabs[oi], nt = next.tabs[ni];
      if (JSON.stringify(ot.path.concat(['sections'])) === key) target = nt.path.concat(['sections']);
      if (!target && JSON.stringify(ot.path.slice(0, -1)) === key) target = nt.path.slice(0, -1);
    });
    if (!target){
      target = next.base.concat(path.slice(old.base.length));
      if (!Array.isArray(specValueAt(newObj, target))) target = next.base;
    }
    return existing(target);
  }
  fields(page(oldObj), page(newObj), ['title', 'skin'], object(newObj).page ? ['page'] : [], 'page');
  var match = pairs(old.refs, next.refs, function(a, b){ return heading(a) === heading(b); }, similarity);
  next.refs.forEach(function(ref, j){
    var label = heading(ref) || 'section ' + (j + 1), path = ref.path;
    if (!match.matches.has(j)){ add(path, 'added', 'section ' + label + ' added'); return; }
    var prev = old.refs[match.matches.get(j)];
    var a = object(prev.value.diagram), b = object(ref.value.diagram), dp = ref.diagram;
    var an = object(a.nodes), bn = object(b.nodes);
    Object.keys(bn).forEach(function(id){
      var np = dp.concat(['nodes', id]);
      if (!Object.prototype.hasOwnProperty.call(an, id)) add(np, 'added', label + ': node ' + id + ' added');
      else allFields(an[id], bn[id], np, label + ': node ' + id);
    });
    Object.keys(an).forEach(function(id){
      if (!Object.prototype.hasOwnProperty.call(bn, id)) add(dp.concat(['nodes']), 'removed', label + ': node ' + id + ' removed');
    });
    function endpoints(e){ e = object(e); return JSON.stringify([e.from, e.to]); }
    compareList(a.edges, b.edges, dp.concat(['edges']), function(e){
      return e.from + '->' + e.to + (e.kind ? '(' + e.kind + ')' : '');
    }, label + ': edge', ['from', 'to'], endpoints);
    var as = list(a.steps), bs = list(b.steps);
    if (as.length !== bs.length) add(dp.concat(['steps']), 'changed', label + ': step count changed (' + as.length + ' → ' + bs.length + ')');
    bs.forEach(function(step, i){
      if (i < as.length) allFields(as[i], step, dp.concat(['steps', i]), label + ': step ' + (i + 1));
    });
    compareList(a.panels, b.panels, dp.concat(['panels']), function(p){ return p.id; }, label + ': panel', ['id']);
    compareList(object(prev.value.contract).fields, object(ref.value.contract).fields,
      path.concat(['contract', 'fields']), function(f){ return f.k; }, label + ': contract field', ['k']);
  });
  old.refs.forEach(function(ref, i){
    if (match.used.has(i)) return;
    var parent = ref.path.slice(0, -1), target = container(parent), order;
    /* Place a removed section before its next surviving old neighbour. */
    for (var k = i + 1; k < old.refs.length; k++){
      if (JSON.stringify(old.refs[k].path.slice(0, -1)) !== JSON.stringify(parent)) continue;
      var found = -1;
      match.matches.forEach(function(oi, ni){ if (oi === k) found = ni; });
      if (found >= 0){
        if (JSON.stringify(next.refs[found].path.slice(0, -1)) !== JSON.stringify(target)) continue;
        order = ranks.get(JSON.stringify(next.refs[found].path)) - 0.5;
        break;
      }
    }
    add(target, 'removed', 'section ' + (heading(ref) || 'section ' + (i + 1)) + ' removed', order);
  });
  next.tabs.forEach(function(t, i){
    if (!tabs.matches.has(i)) add(t.path.concat(['label']), 'added', 'tab ' + t.value.label + ' added');
  });
  old.tabs.forEach(function(t, i){
    if (!tabs.used.has(i)) add(container(t.path.slice(0, -1)), 'removed', 'tab ' + t.value.label + ' removed');
  });
  findings.sort(function(a, b){ return a.order - b.order || a.seq - b.seq; });
  return findings.map(function(f){ return {path: f.path, kind: f.kind, text: f.text}; });
}

function diffSpecTexts(baselineText, currentText){
  var oldObj, newObj;
  try { oldObj = JSON.parse(baselineText); }
  catch (ex){ return {error: 'baseline JSON is unparseable'}; }
  try { newObj = JSON.parse(currentText); }
  catch (ex){ return {error: 'current JSON is unparseable'}; }
  return {findings: diffSpecs(oldObj, newObj)};
}

/* ---------------- tab management ----------------
   Tabs are addressed by BLOCK index (the position in the page's
   blocks/sections list — the same index the engine bakes into each tab
   button's id "tab-<block>-<tab>") plus the tab index inside that
   block's tabs list. */

function builderTabPath(raw, blockIdx, tabIdx){
  var base, page;
  if (raw && raw.page){ page = raw.page; base = ['page']; }
  else if (raw && (raw.blocks || raw.sections)){ page = raw; base = []; }
  else return null;
  var key = page.blocks ? 'blocks' : 'sections';
  var block = (page[key] || [])[blockIdx];
  if (!block || !Array.isArray(block.tabs) || !block.tabs[tabIdx]) return null;
  return base.concat([key, blockIdx, 'tabs', tabIdx]);
}

var BUILDER_TAB_TEMPLATE = [
  '{',
  '  "label": "New tab",',
  '  "sections": [' + BUILDER_SECTION_TEMPLATE.split('\n').join('\n  ') + ']',
  '}'
].join('\n');

/* a whole tabs container: two tabs, one starter section each — the
   "+ tab" button on a selected tab grows it from there */
var BUILDER_TABS_TEMPLATE = [
  '{',
  '  "tabs": [',
  '    ' + BUILDER_TAB_TEMPLATE.replace('"New tab"', '"Tab one"').split('\n').join('\n    ') + ',',
  '    ' + BUILDER_TAB_TEMPLATE.replace('"New tab"', '"Tab two"').split('\n').join('\n    '),
  '  ]',
  '}'
].join('\n');

function planAddTabs(text, raw){
  /* append a tabs container to the page's block list — same shape rules
     as planAddSection */
  var base, page;
  if (raw && raw.page){ page = raw.page; base = ['page']; }
  else if (raw && (raw.blocks || raw.sections)){ page = raw; base = []; }
  else if (raw && raw.nodes && raw.rows)
    return {error: 'this spec is a bare diagram — wrap it as {"page": {"blocks": [ {...} ]}} to hold tabs'};
  else return {error: 'no page to add tabs to'};
  var key = page.blocks ? 'blocks' : 'sections';
  if (!jsonLocate(text, base.concat([key])))
    return {error: 'could not find the ' + key + ' list in the editor text'};
  var r = jsonInsertMember(text, base.concat([key]), null, BUILDER_TABS_TEMPLATE);
  if (!r) return {error: 'could not edit the ' + key + ' list in the editor text'};
  return {text: r.text, start: r.start, end: r.end, kind: 'tabs',
          block: (page[key] || []).length,
          index: specSectionPaths(raw).length};
}

function planAddTab(text, raw, blockIdx, afterIdx){
  /* insert a renderable tab (one starter section) directly after the
     tab the operator is looking at */
  var path = builderTabPath(raw, blockIdx, afterIdx);
  if (!path) return {error: 'tab not found — reselect and try again'};
  var tabsPath = path.slice(0, -1);
  var r = jsonInsertArrayItemAfter(text, tabsPath, afterIdx, BUILDER_TAB_TEMPLATE);
  if (!r) return {error: 'could not edit the tabs list in the editor text'};
  return {text: r.text, start: r.start, end: r.end, kind: 'tab',
          block: blockIdx, index: afterIdx + 1};
}

function planDeleteTab(text, raw, blockIdx, tabIdx){
  var path = builderTabPath(raw, blockIdx, tabIdx);
  if (!path) return {error: 'tab not found — reselect and try again'};
  var tabsPath = path.slice(0, -1);
  var tabs = specValueAt(raw, tabsPath);
  if (Array.isArray(tabs) && tabs.length === 1)
    return {error: 'this is the block\u2019s last tab — delete its sections instead, or remove the whole tabs block in the JSON'};
  var r = jsonRemoveMember(text, tabsPath, tabIdx);
  if (!r) return {error: 'could not edit the tabs list in the editor text'};
  return r;
}

function planMoveTab(text, raw, blockIdx, tabIdx, delta){
  var path = builderTabPath(raw, blockIdx, tabIdx);
  if (!path) return {error: 'tab not found — reselect and try again'};
  var tabsPath = path.slice(0, -1);
  var tabs = specValueAt(raw, tabsPath);
  var to = tabIdx + delta;
  if (to < 0 || to >= tabs.length) return {error: 'already at that end'};
  var r = builderRewrite(text, raw, tabsPath, function(copy){
    var item = copy.splice(tabIdx, 1)[0];
    copy.splice(to, 0, item);
  });
  if (r.error) return r;
  r.kind = 'tab'; r.block = blockIdx; r.index = to;
  return r;
}

/* ---------------- reordering ---------------- */

/* swap two items of one JSON array textually — each item keeps its own
   formatting, only the two spans trade places. Returns the swapped text
   plus the new spans: first = the slot at the SMALLER index, second = the
   slot at the larger. */
function jsonSwapListItems(text, listPath, i, j){
  if (i === j) return null;
  if (i > j){ var t = i; i = j; j = t; }
  var a = jsonLocate(text, listPath.concat([i]));
  var b = jsonLocate(text, listPath.concat([j]));
  if (!a || !b) return null;
  return {
    text: text.slice(0, a.start) + text.slice(b.start, b.end) +
          text.slice(a.end, b.start) + text.slice(a.start, a.end) + text.slice(b.end),
    first: {start: a.start, end: a.start + (b.end - b.start)},
    second: {start: b.end - (a.end - a.start), end: b.end}
  };
}

/* move a section one slot within ITS OWN list (the top-level blocks list,
   or its tab's sections list). A neighbor blocks-list entry may be a tabs
   container — the move hops over it whole. Returns newPath (the section's
   list slot after the move); the caller recomputes the flat ordinal from
   it, because hopping a tabs container shifts ordinals by its section
   count. */
function planMoveSection(text, raw, sectionIdx, delta){
  var rec = specSectionPaths(raw)[sectionIdx];
  if (!rec) return {error: 'section not found — reselect and try again'};
  var spath = rec.section;
  if (!spath.length) return {error: 'a bare-diagram page has only one section'};
  var listPath = spath.slice(0, -1);
  var idx = spath[spath.length - 1];
  var list = specValueAt(raw, listPath);
  if (!Array.isArray(list)) return {error: 'section list not found in the editor text'};
  var to = idx + delta;
  if (to < 0) return {error: 'already first in its list'};
  if (to >= list.length) return {error: 'already last in its list'};
  var swap = jsonSwapListItems(text, listPath, idx, to);
  if (!swap) return {error: 'could not locate both sections in the editor text'};
  var span = delta < 0 ? swap.first : swap.second;
  return {text: swap.text, start: span.start, end: span.end,
          kind: 'section', newPath: listPath.concat([to])};
}

/* swap the LAYOUT positions of two nodes: every appearance in rows
   (slots and stacks) and floats trades ids. Node definitions, edges, and
   steps keep their ids — only placement moves. */
function planSwapNodes(text, raw, sectionIdx, idA, idB){
  if (idA === idB) return {error: 'drop on a DIFFERENT node to swap places'};
  var rec = specSectionPaths(raw)[sectionIdx];
  if (!rec) return {error: 'section not found — reselect and try again'};
  var d = specValueAt(raw, rec.diagram);
  if (!d) return {error: 'no diagram in this section'};
  var found = {a: false, b: false};
  function sw(id){
    if (id === idA){ found.a = true; return idB; }
    if (id === idB){ found.b = true; return idA; }
    return id;
  }
  var rows = Array.isArray(d.rows) ? d.rows.map(function(row){
    if (!Array.isArray(row)) return row;
    return row.map(function(slot){ return Array.isArray(slot) ? slot.map(sw) : sw(slot); });
  }) : null;
  var floats = Array.isArray(d.floats) ? d.floats.map(function(f){
    if (!f || typeof f !== 'object' || typeof f.id !== 'string') return f;
    var nid = sw(f.id);
    if (nid === f.id) return f;
    var copy = {};
    Object.keys(f).forEach(function(k){ copy[k] = f[k]; });
    copy.id = nid;
    return copy;
  }) : null;
  if (!found.a || !found.b)
    return {error: 'node "' + (found.a ? idB : idA) + '" has no layout slot (rows or floats) to swap'};
  var pairs = [];
  if (rows && JSON.stringify(rows) !== JSON.stringify(d.rows)) pairs.push(['rows', JSON.stringify(rows)]);
  if (floats && JSON.stringify(floats) !== JSON.stringify(d.floats)) pairs.push(['floats', JSON.stringify(floats)]);
  if (!pairs.length) return {error: 'nothing changed'};
  var plan = planSetFields(text, raw, rec.diagram, pairs);
  if (plan.error) return plan;
  plan.kind = 'node';
  return plan;
}

/* ---------------- multi-select: bulk planners ----------------
   A multi-selection is HOMOGENEOUS (one kind) — mixed-kind bulk deletes
   interact with cascades (a node delete prunes edges/steps) in ways that
   silently invalidate sibling targets. Deletes apply highest-index-first
   per section so earlier deletions cannot shift later targets. */
var BUILDER_MULTI_KINDS = ['node', 'edge', 'step', 'panel', 'bullet', 'crow'];

function builderDeletePlan(text, raw, t){
  if (t.kind === 'tab') return planDeleteTab(text, raw, t.block, t.tab);
  if (t.kind === 'node') return planDeleteNode(text, raw, t.section, t.id);
  if (t.kind === 'edge') return planDeleteEdge(text, raw, t.section, t.index);
  if (t.kind === 'step') return planDeleteStep(text, raw, t.section, t.index);
  if (t.kind === 'panel') return planDeletePanel(text, raw, t.section, t.index);
  var rec = specSectionPaths(raw)[t.section];
  if (!rec) return {error: 'no such section'};
  if (t.kind === 'bullet') return planDeleteListItem(text, raw, rec.section.concat(['bullets']), t.index);
  if (t.kind === 'para'){
    var sec = specValueAt(raw, rec.section);
    if (sec && typeof sec.text === 'string') return planSetField(text, raw, rec.section, 'text', null);
    return planDeleteListItem(text, raw, rec.section.concat(['text']), t.index);
  }
  if (t.kind === 'crow') return planDeleteListItem(text, raw, rec.section.concat(['contract', 'fields']), t.index);
  return planDeleteSection(text, raw, t.section);
}

function planBulkSetField(text, targets, key, valueTextOrNull){
  var cur = text;
  for (var i = 0; i < targets.length; i++){
    var raw;
    try { raw = JSON.parse(cur); }
    catch (ex){ return {error: 'bulk stopped: the JSON no longer parses (' + ex.message + ')'}; }
    var path = builderTargetPath(raw, targets[i]);
    if (!path) return {error: 'selection ' + (i + 1) + ' no longer resolves — re-render and reselect'};
    var plan = planSetField(cur, raw, path, key, valueTextOrNull);
    if (plan.error) return {error: 'selection ' + (i + 1) + ': ' + plan.error};
    cur = plan.text;
  }
  return {text: cur, count: targets.length};
}

function planBulkDelete(text, targets){
  var list = targets.slice().sort(function(a, b){
    if ((a.section || 0) !== (b.section || 0)) return (b.section || 0) - (a.section || 0);
    return (typeof b.index === 'number' ? b.index : 0) - (typeof a.index === 'number' ? a.index : 0);
  });
  var cur = text;
  for (var i = 0; i < list.length; i++){
    var raw;
    try { raw = JSON.parse(cur); }
    catch (ex){ return {error: 'bulk stopped: the JSON no longer parses (' + ex.message + ')'}; }
    var plan = builderDeletePlan(cur, raw, list[i]);
    if (plan.error) return {error: 'selection ' + (i + 1) + ': ' + plan.error};
    cur = plan.text;
  }
  return {text: cur, count: list.length};
}

/* ---------------- step contract editing ----------------
   A step's membership: hops (edge / edges), lit nodes (nodes), and
   panel patches (panels). Toggles normalize the hop shape: zero hops
   removes the key (edgeless steps are legal), one hop stores
   edge: "a->b", two or more store edges: [...]. */

function builderStepHops(st){
  /* tolerate the malformed both-keys shape: merge edge and edges so a
     later toggle's rebuild cannot silently drop listed hops */
  if (!st) return [];
  var out = [];
  if (typeof st.edge === 'string') out.push(st.edge);
  if (Array.isArray(st.edges)) st.edges.forEach(function(k){
    if (typeof k === 'string' && out.indexOf(k) < 0) out.push(k);
  });
  return out;
}

function builderStepAt(raw, sectionIdx, stepIdx){
  var rec = specSectionPaths(raw)[sectionIdx];
  if (!rec) return null;
  var d = specValueAt(raw, rec.diagram);
  if (!d || !Array.isArray(d.steps) || !d.steps[stepIdx]) return null;
  return {rec: rec, d: d, st: d.steps[stepIdx],
          path: rec.diagram.concat(['steps', stepIdx])};
}

function planStepToggleHop(text, raw, sectionIdx, stepIdx, key){
  var got = builderStepAt(raw, sectionIdx, stepIdx);
  if (!got) return {error: 'step not found — reselect and try again'};
  var hops = builderStepHops(got.st);
  var has = hops.indexOf(key) >= 0;
  if (!has){
    var known = (got.d.edges || []).some(function(e){ return e && builderEdgeKey(e) === key; });
    if (!known) return {error: 'no edge "' + key + '" in this diagram'};
  }
  var next = has ? hops.filter(function(k){ return k !== key; }) : hops.concat([key]);
  var r = builderRewrite(text, raw, got.path, function(st){
    delete st.edge; delete st.edges;
    if (next.length === 1) st.edge = next[0];
    else if (next.length > 1) st.edges = next;
  });
  if (r.error) return r;
  r.added = !has;
  return r;
}

function planStepToggleNode(text, raw, sectionIdx, stepIdx, nodeId){
  var got = builderStepAt(raw, sectionIdx, stepIdx);
  if (!got) return {error: 'step not found — reselect and try again'};
  var list = Array.isArray(got.st.nodes) ? got.st.nodes : [];
  var has = list.indexOf(nodeId) >= 0;
  if (!has && !(got.d.nodes && Object.prototype.hasOwnProperty.call(got.d.nodes, nodeId)))
    return {error: 'no node "' + nodeId + '" in this diagram'};
  var r = builderRewrite(text, raw, got.path, function(st){
    var next = (Array.isArray(st.nodes) ? st.nodes : []).filter(function(n){ return n !== nodeId; });
    if (!has) next.push(nodeId);
    if (next.length) st.nodes = next; else delete st.nodes;
  });
  if (r.error) return r;
  r.added = !has;
  return r;
}

function planStepTogglePanel(text, raw, sectionIdx, stepIdx, panelId){
  var got = builderStepAt(raw, sectionIdx, stepIdx);
  if (!got) return {error: 'step not found — reselect and try again'};
  var has = !!(got.st.panels && Object.prototype.hasOwnProperty.call(got.st.panels, panelId));
  if (!has && !(got.d.panels || []).some(function(p){ return p && p.id === panelId; }))
    return {error: 'no panel "' + panelId + '" in this diagram'};
  var r = builderRewrite(text, raw, got.path, function(st){
    if (has){
      delete st.panels[panelId];
      if (!Object.keys(st.panels).length) delete st.panels;
    } else {
      if (!st.panels) st.panels = {};
      st.panels[panelId] = {};
    }
  });
  if (r.error) return r;
  r.added = !has;
  return r;
}

function planStepSetPanelPatch(text, raw, sectionIdx, stepIdx, panelId, patchText){
  /* replace one panel patch with operator-supplied JSON (an object) */
  var got = builderStepAt(raw, sectionIdx, stepIdx);
  if (!got) return {error: 'step not found — reselect and try again'};
  var patch;
  try { patch = JSON.parse(patchText); }
  catch (ex){ return {error: 'the patch is not valid JSON (' + ex.message + ')'}; }
  if (!patch || typeof patch !== 'object' || Array.isArray(patch))
    return {error: 'a panel patch is a JSON object'};
  if (!(got.st.panels && Object.prototype.hasOwnProperty.call(got.st.panels, panelId)))
    return {error: 'panel "' + panelId + '" is not in this step'};
  return builderRewrite(text, raw, got.path.concat(['panels', panelId]), function(copy, _unused){
    /* builderRewrite mutates a copy in place; replace all fields */
    Object.keys(copy).forEach(function(k){ delete copy[k]; });
    Object.keys(patch).forEach(function(k){ copy[k] = patch[k]; });
  });
}

