function mermaidToSpec(text){
  if (typeof text !== 'string') throw new Error('line 1: expected mermaid text');
  /* Match the CLI: the first mermaid fence wins, even if it is not a sequence. */
  var fence = /^```mermaid\s*$([\s\S]*?)^```\s*$/m.exec(text);
  var lines = (fence ? fence[1] : text).split(/\r\n|[\n\r\v\f\x1c-\x1e\x85\u2028\u2029]/)
    .map(function(ln){ return ln.trim(); }).filter(function(ln){ return ln; });
  if (!lines.length || lines[0] !== 'sequenceDiagram')
    throw new Error('line 1: not a sequenceDiagram (first line is ' +
      JSON.stringify(lines[0] || '<empty>') + '); only mermaid sequenceDiagram input is supported');
  var order = [], titles = Object.create(null), messages = [], todos = [];
  var depth = 0, skipped = 0, header = null, blockLine = 0, n = 1;
  function ensure(pid, title){
    var id = pid.toLowerCase().replace(/[^a-z0-9]+/g, '');
    if (!id) throw new Error('line ' + n + ': participant id ' + JSON.stringify(pid) + ' slugs to nothing');
    if (!Object.prototype.hasOwnProperty.call(titles, id)){
      order.push(id);
      titles[id] = title || pid;
    } else if (title) titles[id] = title;
    return id;
  }
  for (var i = 1; i < lines.length; i++){
    var ln = lines[i];
    n = i + 1; /* CLI line numbers count nonblank lines. */
    if (ln === 'autonumber') continue;
    if (/^Note\b/i.test(ln)){
      todos.push('note not converted: ' + ln);
      continue;
    }
    var b = /^(alt|opt|loop|par)\b\s*(.*)$/.exec(ln);
    if (b){
      if (!depth){ header = (b[1] + ' ' + b[2]).trim(); skipped = 0; blockLine = n; }
      depth++;
      continue;
    }
    if (ln === 'else' || ln.indexOf('else ') === 0){
      if (!depth) throw new Error('line ' + n + ": 'else' outside a block");
      continue;
    }
    if (ln === 'end'){
      if (!depth) throw new Error('line ' + n + ": 'end' without an open block");
      depth--;
      if (!depth) todos.push(header + ' block not converted (' + skipped + ' message(s) inside) — add by hand');
      continue;
    }
    var p = /^participant\s+(\S+?)(?:\s+as\s+(.+?))?\s*$/.exec(ln);
    if (p){
      if (!depth) ensure(p[1], p[2]);
      continue;
    }
    var m = /^(\S+?)\s*(-->>|->>)\s*(\S+?)\s*:\s*(.+?)\s*$/.exec(ln);
    if (m){
      if (depth){ skipped++; continue; }
      messages.push({from: ensure(m[1]), to: ensure(m[3]), ret: m[2] === '-->>', text: m[4]});
      continue;
    }
    throw new Error('line ' + n + ': unsupported syntax ' + JSON.stringify(ln) +
      ' — supported: participant, ->> / -->> messages, autonumber, alt/opt/loop/par blocks, Note');
  }
  if (depth) throw new Error('line ' + blockLine + ': unclosed alt/opt/loop/par block');
  if (!messages.length) throw new Error('line ' + n + ': no messages found outside alt/opt/loop/par blocks');
  var edges = [], pairs = Object.create(null), steps = [];
  messages.forEach(function(m){
    var key = m.from + '->' + m.to;
    if (!pairs[key]){
      var kind = /https?|POST|GET/i.test(m.text) ? 'https' :
        /publish|subscribe|mqtt|qos/i.test(m.text) ? 'mqtt' : 'int';
      var edge = {from: m.from, to: m.to, kind: kind, label: m.text};
      if (m.ret) edge.ret = true;
      pairs[key] = true;
      edges.push(edge);
    }
    steps.push({edge: key, text: m.text});
  });
  var half = Math.floor((order.length + 1) / 2), rows = [order.slice(0, half)], nodes = {};
  if (order.length > half) rows.push(order.slice(half));
  order.forEach(function(id){ nodes[id] = {title: titles[id], sub: '', icon: 'gear', tint: 'cmd'}; });
  var title = 'Converted sequence';
  return {page: {title: title, sections: [{heading: title,
    text: ['Skeleton generated by mermaid2spec.py — enrich titles, subs, icons, tints, protocols, and prose before use.'],
    diagram: {view: 'ambient', nodes: nodes, rows: rows, edges: edges, steps: steps}
  }]}, todos: todos};
}

function starterCountLine(spec){
  var nodes = 0, steps = 0, panels = 0;
  specSectionPaths(spec).forEach(function(rec){
    var d = specValueAt(spec, rec.diagram);
    if (!d) return;
    nodes += Object.keys(d.nodes || {}).length;
    steps += (d.steps || []).length;
    panels += (d.panels || []).length;
  });
  return nodes + (nodes === 1 ? ' node · ' : ' nodes · ') +
    steps + (steps === 1 ? ' step · ' : ' steps · ') + panels + (panels === 1 ? ' panel' : ' panels');
}
/* Search the source tree, including nodes omitted from layout and hidden
   tabs. Keep raw paths and rendered section ordinals together. */
function builderOutline(raw, query){
  var entries = [], terms = String(query || '').toLowerCase().trim().split(/\s+/).filter(Boolean);
  specSectionPaths(raw).forEach(function(rec, section){
    var sec = specValueAt(raw, rec.section) || {}, d = specValueAt(raw, rec.diagram) || {};
    var ti = rec.section.indexOf('tabs');
    var tab = ti >= 0 ? {block: rec.section[ti - 1], tab: rec.section[ti + 1]} : null;
    var parent = ti >= 0 ? specValueAt(raw, rec.section.slice(0, ti + 2)) : null;
    var context = (parent && parent.label ? parent.label + ' / ' : '') + (sec.heading || 'Section ' + (section + 1));
    function add(kind, label, extra){
      var target = Object.assign({section: section, kind: kind}, extra || {});
      var path = builderTargetPath(raw, target);
      var haystack = (kind + ' ' + label + ' ' + context + ' ' + builderPathString(path)).toLowerCase();
      if (terms.every(function(term){ return haystack.indexOf(term) >= 0; }))
        entries.push({label: label, context: context, target: target, path: path, tab: tab});
    }
    add('section', sec.heading || 'Section ' + (section + 1));
    Object.keys(d.nodes || {}).forEach(function(id){ add('node', ((d.nodes[id] || {}).title || id) + ' · ' + id, {id: id}); });
    Object.keys(d.groups || {}).forEach(function(id){ add('group', ((d.groups[id] || {}).title || id) + ' · ' + id, {id: id}); });
    (Array.isArray(d.edges) ? d.edges : []).forEach(function(e, index){
      if (e) add('edge', e.from + ' → ' + e.to + (e.label ? ' · ' + e.label : ''), {index: index});
    });
    (Array.isArray(d.panels) ? d.panels : []).forEach(function(p, index){
      if (p) add('panel', (p.title || p.id) + ' · ' + p.type + ' · ' + p.id, {index: index});
    });
    (Array.isArray(d.steps) ? d.steps : []).forEach(function(s, index){
      if (s) add('step', (index + 1) + '. ' + (s.text || s.id || 'Untitled step'), {index: index});
    });
  });
  return entries;
}
function builderInsertTargetText(raw, sectionIdx){
  /* the descriptive part of the insert-target label: "section N · heading",
     prefixed with the tab name when the target section lives inside a tabs
     block. A blank/whitespace tab label falls back to "tab N". Returns null
     when the section ordinal has no section. */
  var rec = specSectionPaths(raw || {})[sectionIdx];
  if (!rec) return null;
  var sec = specValueAt(raw, rec.section);
  var name = sec && typeof sec.heading === 'string' && sec.heading ? ' · ' + sec.heading : '';
  var tabName = '';
  var path = rec.section;
  var ti = path.indexOf('tabs');
  if (ti >= 0 && typeof path[ti + 1] === 'number'){
    var tabsArr = specValueAt(raw, path.slice(0, ti + 1));
    var tab = Array.isArray(tabsArr) ? tabsArr[path[ti + 1]] : null;
    var raw2 = tab && typeof tab.label === 'string' ? tab.label.trim() : '';
    var label = raw2 || ('tab ' + (path[ti + 1] + 1));
    tabName = 'tab “' + label + '” › ';
  }
  return 'into ' + tabName + 'section ' + (sectionIdx + 1) + name;
}

