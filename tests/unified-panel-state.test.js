'use strict';
/* Per-step setup changes for panel types that opt in with `unified: true`:
   the effective-declaration helper, the player heading, validation,
   compatibility detection, and proof that every existing spec is unchanged. */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {readSource, entrypoint} = require('../tools/source-loader.cjs');

const ROOT = path.join(__dirname, '..');
const C = {URL, TextEncoder, console};
vm.createContext(C);
for (const file of ['compatibility.js', 'canon.js', 'validator.js', 'engine.js'])
  vm.runInContext(readSource(file), C, {filename: file});
const plain = value => JSON.parse(JSON.stringify(value));

function gaugeDiagram(steps){
  return {nodes: {a: {}}, rows: [['a']],
    panels: [{id: 'g', type: 'gauge', title: 'Draw', unit: 'mA', max: 100, initial: {value: 50}}],
    steps: steps.map(panels => ({nodes: ['a'], panels: panels ? {g: panels} : undefined}))};
}
function effective(d){
  return C.foldPanelStates(d).g.map(state => C.panelEffectiveDeclaration(d.panels[0], state));
}
const warningsOf = d => C.validate(C.normalize(d)).warnings;

test('existing specs fold, validate, render and report compatibility exactly as before the feature', () => {
  /* tests/fixtures/unified-noop-baseline.json was generated by
     tests/fixtures/build_unified_baseline.cjs with the runtime of 5744ca77
     (main when the feature branch was cut): folded states, validator output,
     detected compatibility features, and every panel's heading and HTML at
     every step of every path, for every starter and example including
     *.spec.v2.json. Specs edited after the baseline are skipped by content hash. */
  const {fingerprint} = require('./fixtures/build_unified_baseline.cjs');
  const baseline = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/unified-noop-baseline.json'), 'utf8'));
  const now = fingerprint(ROOT, ROOT);
  let compared = 0;
  for (const rel of Object.keys(baseline)) {
    if (!now[rel] || now[rel].spec !== baseline[rel].spec) continue;
    assert.deepEqual(now[rel], baseline[rel], rel + ' changed');
    compared++;
  }
  assert.ok(compared >= 70, 'compared ' + compared + ' specs against the baseline');
  assert.ok(Object.keys(baseline).some(rel => /\.spec\.v\d+\.json$/.test(rel)), 'versioned specs are included');
});

test('unflagged types get their own declaration object back, whatever the state holds', () => {
  for (const type of C.PanelRegistry.types()) {
    if (C.PanelRegistry.get(type).unified) continue;
    const panel = {id: 'p', type, title: 'T', max: 1, columns: [], leds: []};
    const state = {title: 'X', max: 2, columns: 'bad', leds: 'on', id: 'q', type: 'gauge'};
    assert.equal(C.panelEffectiveDeclaration(panel, state), panel, type);
    assert.equal(C.panelUnifiedFields(type), null, type);
  }
});

test('gauge setup fields carry, enterOnce lasts one step and null restores the declared value', () => {
  const d = gaugeDiagram([{max: 200}, {enterOnce: {unit: 'A', title: 'Peak'}}, null, {max: null, title: 'Late'}, {value: 80}]);
  const decl = effective(d).map(p => [p.max, p.unit, p.title]);
  assert.deepEqual(plain(decl), [[200, 'mA', 'Draw'], [200, 'A', 'Peak'], [200, 'mA', 'Draw'], [100, 'mA', 'Late'], [100, 'mA', 'Late']]);
  const html = C.foldPanelStates(d).g.map(state => C.softwarePanelHTML(d.panels[0], state));
  assert.match(html[0], /width:25\.0%/);
  assert.match(html[1], /gaugeunit">A</);
  assert.match(html[3], /width:50\.0%/);
  assert.deepEqual(plain(C.panelUnifiedFields('gauge')), ['unit', 'max', 'title']);
});

test('identity and frame fields are never laid over the declaration', () => {
  const panel = {id: 'g', type: 'gauge', max: 10, visible: false, brand: false, initial: {value: 1}};
  const state = {id: 'other', type: 'leds', initial: {}, visible: true, brand: {companyName: 'X'}, value: 3, label: 'not setup'};
  assert.equal(C.panelEffectiveDeclaration(panel, state), panel);
  const once = C.panelEffectiveDeclaration(panel, {max: 20});
  assert.notEqual(once, panel);
  assert.deepEqual(plain(once), {id: 'g', type: 'gauge', max: 20, visible: false, brand: false, initial: {value: 1}});
  assert.equal(panel.max, 10, 'the declaration is not mutated');
});

test('alternate paths carry setup changes independently', () => {
  const d = gaugeDiagram([{max: 200}, null, {max: 400}]);
  ['start', 'main-end', 'alt-end'].forEach((id, i) => { d.steps[i].id = id; });
  d.paths = [{id: 'main', steps: ['start', 'main-end']}, {id: 'alt', steps: ['start', 'alt-end']}];
  assert.deepEqual(plain(effective(C.diagramForPath(d, 'main')).map(p => p.max)), [200, 200]);
  assert.deepEqual(plain(effective(C.diagramForPath(d, 'alt')).map(p => p.max)), [200, 400]);
});

test('the player heading follows the effective title and is created and removed as needed', () => {
  function el(){
    return {children: [], parentNode: null, textContent: '', innerHTML: '', className: '',
      classList: {toggle(){}, contains(){ return false; }},
      get firstChild(){ return this.children[0] || null; },
      setAttribute(){}, removeAttribute(){}, querySelector(){ return null; }, querySelectorAll(){ return []; },
      appendChild(c){ c.parentNode = this; this.children.push(c); return c; },
      insertBefore(c, ref){ c.parentNode = this; this.children.splice(this.children.indexOf(ref), 0, c); return c; },
      removeChild(c){ this.children.splice(this.children.indexOf(c), 1); c.parentNode = null; return c; }};
  }
  const sandbox = {console, URL, document: {createElement: el}, CustomEvent: class {}};
  vm.runInNewContext(entrypoint('native').source, sandbox);
  const d = gaugeDiagram([null, {enterOnce: {title: 'Peak'}}, {title: ''}, {title: null}]);
  d.panels[0].title = undefined;
  const aside = el(), ctl = sandbox.buildPanels(aside, d, 'aurora');
  const card = aside.children[0];
  const heading = () => card.children.filter(c => c.className === 'ptitle').map(c => c.textContent);
  assert.deepEqual(heading(), []);
  ctl.setStep(1, false);
  assert.deepEqual(heading(), ['Peak']);
  assert.equal(card.children[0].className, 'ptitle', 'the heading precedes the body');
  ctl.setStep(2, false);
  assert.deepEqual(heading(), []);
  d.panels[0].title = 'Draw';
  const aside2 = el(), ctl2 = sandbox.buildPanels(aside2, d, 'aurora'), card2 = aside2.children[0];
  const heading2 = () => card2.children.filter(c => c.className === 'ptitle').map(c => c.textContent);
  assert.deepEqual(heading2(), ['Draw']);
  ctl2.setStep(1, false);
  assert.deepEqual(heading2(), ['Peak']);
  ctl2.setStep(2, false);
  assert.deepEqual(heading2(), [], 'an empty title hides the heading');
  ctl2.setStep(3, false);
  assert.deepEqual(heading2(), ['Draw'], 'null restores the declared title');
  ctl.destroy();
  ctl2.destroy();
});

test('gauge setup fields in patches validate silently', () => {
  const d = gaugeDiagram([{max: 200, unit: 'A', title: 'x'}, {enterOnce: {max: 'bad'}}, {max: null}]);
  assert.deepEqual(plain(warningsOf(d).filter(w => w.includes('.panels.g'))), []);
});

test('a unified type with declaration rules has its overrides checked at the patch path', () => {
  /* A test-only type exercises the shared validator path: its own patch rule
     rejects unknown keys, its declaration rule checks `limit`. */
  const T = {URL, TextEncoder, console};
  vm.createContext(T);
  vm.runInContext(readSource('validator.js'), T, {filename: 'validator.js'});
  vm.runInContext(`PanelRegistry.define('probe', {
    unified: true,
    authoring: {setupFields: [['limit', 'num'], ['initial', 'json']]},
    validateDeclaration: function (p, path, warnings) {
      if (p.limit != null && typeof p.limit !== 'number') warnings.push(path + '.limit: expected a number');
      if (p.other != null) warnings.push(path + '.other: declared once');
      return {limit: p.limit};
    },
    validatePatch: function (patch, path, panel, warnings, context) {
      Object.keys(patch).forEach(function (key) {
        if (key !== 'value' && key !== 'enterOnce') warnings.push(path + '.' + key + ': unknown field');
      });
      if (typeof patch.value === 'number' && patch.value > context.limit) warnings.push(path + '.value: above ' + context.limit);
    },
  });`, T);
  const d = {nodes: {a: {}}, rows: [['a']], panels: [{id: 'p', type: 'probe', limit: 10, other: 1}],
    steps: [{nodes: ['a'], panels: {p: {limit: 'x'}}}, {nodes: ['a'], panels: {p: {limit: 50, value: 20}}},
      {nodes: ['a'], panels: {p: {value: 60}}}, {nodes: ['a'], panels: {p: {enterOnce: {limit: 5}, value: 7}}},
      {nodes: ['a'], panels: {p: {limit: null, value: 20, label: 'y'}}}]};
  const steps = T.validate(T.normalize(d)).warnings.filter(w => w.includes('.steps['));
  assert.deepEqual(plain(steps.map(w => w.replace(/^.*\.steps/, 'steps'))), [
    'steps[0].panels.p.limit: expected a number',
    'steps[2].panels.p.value: above 50',
    'steps[3].panels.p.value: above 5',
    'steps[4].panels.p.label: unknown field',
    'steps[4].panels.p.value: above 10',
  ]);
});

test('compatibility reports per-step setup changes only for unified types that use them', () => {
  const F = C.FlowviewCompatibility, uses = d => F.detect(d).includes('flow.panel-setup-steps');
  assert.equal(F.features['flow.panel-setup-steps'].since, '0.2.0');
  assert.equal(uses(gaugeDiagram([{value: 3}, null])), false);
  assert.equal(uses(gaugeDiagram([{max: 3}])), true);
  assert.equal(uses(gaugeDiagram([{enterOnce: {title: 'x'}}])), true);
  const initial = gaugeDiagram([null]);
  initial.panels[0].initial.unit = 'A';
  assert.equal(uses(initial), true);
  const leds = {nodes: {a: {}}, rows: [['a']], panels: [{id: 'l', type: 'leds', leds: [{id: 'title'}]}],
    steps: [{nodes: ['a'], panels: {l: {title: 'on', leds: 'on'}}}]};
  assert.equal(uses(leds), false, 'unflagged types are never reported');
  assert.ok(F.stamp(gaugeDiagram([{max: 3}])).page.flowview.features.includes('flow.panel-setup-steps'));
});
