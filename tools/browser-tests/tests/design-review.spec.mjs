import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {test,expect,paste} from '../helpers/test.mjs';
import {repo} from '../helpers/prepare.mjs';
const source=await readFile(path.join(repo,'examples/design-review/design-review.spec.json'),'utf8');
const diagram=s=>s.page.sections[0].diagram;
const chip=(root,index)=>root.locator('.schip[data-step-source="'+index+'"]').first();
async function standalone(page,server,raw){
  await writeFile(path.join(server.root,'review.json'),JSON.stringify(raw));
  execFileSync('python3',[path.join(repo,'tools/inject.py'),path.join(server.root,'review.json'),path.join(repo,'template/flowview.html'),path.join(server.root,'review.html')]);
  await page.goto(server.origin+'/review.html');return page.locator('.docview');
}
