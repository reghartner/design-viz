test('desktop author can change review controls and move a Home device at one step with Undo',async({page,server},testInfo)=>{
  await page.goto(server.origin+'/workbench.html');await paste(page,source);
  const root=page.locator('#docview'),guide=page.getByRole('region',{name:'Inspect',exact:true});
  await page.locator('#editor-tab-steps').click();await page.locator('.playback-settings summary').click();
  await page.locator('#steps-show-ids').check();await expect(root.locator('.stepline .stepid')).toBeVisible();
  await page.locator('#undo-builder').click();await expect(page.locator('#src')).toHaveValue(source);await expect(root.locator('.stepline .stepid')).toBeHidden();
  await page.locator('#steps-path').selectOption('proposed');await page.locator('#steps-list [data-step-index="3"]').click();
  await page.locator('#editor-tab-inspect').click();
  await page.getByRole('combobox',{name:'Review verdict',exact:true}).selectOption('open');
  expect(diagram(JSON.parse(await page.locator('#src').inputValue())).steps[3].verdict).toBe('open');
  await page.locator('#undo-builder').click();await expect(page.locator('#src')).toHaveValue(source);
  await page.locator('#steps-list [data-step-index="3"]').click();
  await guide.locator('summary').filter({hasText:'Gateway placement'}).click();
  const map=guide.locator('.home-edit-map'),device=map.locator('[data-device="gateway"]');
  await expect(device).toBeVisible();await device.scrollIntoViewIfNeeded();
  const before=await device.boundingBox();await page.mouse.move(before.x+before.width/2,before.y+before.height/2);await page.mouse.down();await page.mouse.move(before.x+before.width/2+24,before.y+before.height/2+18,{steps:4});await page.mouse.up();
  const edited=await page.locator('#src').inputValue(),d=diagram(JSON.parse(edited));
  expect(d.panels[0].devices[0]).toEqual(diagram(JSON.parse(source)).panels[0].devices[0]);
  expect(d.steps[3].panels.home.gateway.x).not.toBe(190);expect(d.steps[3].panels.home.gateway.state).toBe('rx');
  await page.locator('#undo-builder').click();await expect(page.locator('#src')).toHaveValue(source);
  await page.locator('#redo-builder').click();await expect(page.locator('#src')).toHaveValue(edited);
  await page.locator('#steps-list [data-step-index="3"]').click();
  await page.screenshot({path:testInfo.outputPath('review-home-editor.png')});
});
